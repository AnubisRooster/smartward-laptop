#!/usr/bin/env python3
"""Writes frontend/src/theme.css: the light theme, made by re-pointing the dark-first Tailwind palette.

The UI is written with zinc/indigo/red/emerald/amber classes. In light mode the light and dark ends of each
scale swap, so every existing class follows the theme without being renamed.
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / "frontend"
theme = (root / "node_modules/tailwindcss/theme.css").read_text()
col = {(m[1], int(m[2])): m[3].strip() for m in re.finditer(r"--color-(zinc|indigo|red|emerald|amber)-(\d+):\s*([^;]+);", theme)}
ZINC = {50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50}
# 500 and 600 stay put on the colours so filled buttons keep their contrast with white text.
TINT = {50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 700: 300, 800: 200, 900: 100, 950: 50}
out = ["/* Generated by scripts/gen_theme.py. Do not edit by hand. */", ':root[data-theme="light"] {']
for name in ["zinc", "indigo", "red", "emerald", "amber"]:
    for k in sorted(k for (n, k) in col if n == name):
        m = (ZINC if name == "zinc" else TINT).get(k, k)
        if m != k:
            out.append(f"  --color-{name}-{k}: {col[(name, m)]};")
out.append("}")
(root / "src/theme.css").write_text("\n".join(out) + "\n")
print("wrote frontend/src/theme.css")
